"""Export a trained CNet to kickdetect/kd_weights.h (C) and kickdetect/weights.json (any language)."""
import os, sys, json, numpy as np, torch
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def carr(name, a):
    a = np.asarray(a, np.float32)
    def rec(x):
        if x.ndim == 0: return repr(float(x)) + "f"
        return "{" + ",".join(rec(y) for y in x) + "}"
    dims = "".join(f"[{d}]" for d in a.shape)
    return f"static const float {name}{dims} = {rec(a)};\n"

def export(model, lat_frames, threshold, out_dir=os.path.join(HERE, "kickdetect"), meta=None, threshold_tempo=None):
    threshold_tempo = threshold if threshold_tempo is None else threshold_tempo
    sd = {k: v.detach().cpu().numpy() for k, v in model.state_dict().items()}
    c1, c2, c3 = sd["c1.weight"].shape[0], sd["c2.weight"].shape[0], sd["c3.weight"].shape[0]; hid = sd["d1.weight"].shape[0]
    h = "/* Generated by tools/export.py - do not edit. */\n#ifndef KD_WEIGHTS_H\n#define KD_WEIGHTS_H\n"
    h += f"#define KD_NB 13\n#define KD_C1 {c1}\n#define KD_C2 {c2}\n#define KD_C3 {c3}\n#define KD_HID {hid}\n#define KD_LAT_FRAMES {lat_frames}\n#define KD_THRESHOLD {threshold}f\n#define KD_THRESHOLD_TEMPO {threshold_tempo}f\n"
    h += carr("kd_w1", sd["c1.weight"]) + carr("kd_b1", sd["c1.bias"]) + carr("kd_w2", sd["c2.weight"]) + carr("kd_b2", sd["c2.bias"])
    h += carr("kd_w3", sd["c3.weight"]) + carr("kd_b3", sd["c3.bias"]) + carr("kd_wd1", sd["d1.weight"]) + carr("kd_bd1", sd["d1.bias"])
    h += carr("kd_wd2", sd["d2.weight"][0]) + f"static const float kd_bd2 = {float(sd['d2.bias'][0])!r}f;\n#endif\n"
    open(os.path.join(out_dir, "kd_weights.h"), "w").write(h)
    js = dict(format="kickdetect-cnn-v1", lat_frames=lat_frames, threshold=threshold, threshold_tempo=threshold_tempo, tempo_beta=3.0, meta=meta or {},
              layers={k: dict(shape=list(v.shape), data=[round(float(x), 7) for x in v.ravel()]) for k, v in sd.items()})
    json.dump(js, open(os.path.join(out_dir, "weights.json"), "w"))
    return sum(v.size for v in sd.values())
